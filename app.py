# ------------------------------------------------------------------ data
@st.cache_data
def load_bank():
    return json.loads(BANK_PATH.read_text(encoding="utf-8"))


BANK = load_bank()
BY_ID = {q["id"]: q for q in BANK}
TOPICS = sorted({q["topic"] for q in BANK})


def normalise(text):
    """Lower-case and drop spaces/hyphens/trailing punctuation for typed answers."""
    return re.sub(r"[\s\-_.!]", "", str(text).lower())


def is_correct(q, response):
    if response is None:
        return False
    if q["pairs"]:
        return all(response.get(k) == v for k, v in q["pairs"].items())
    if q["accept"]:
        return normalise(response) in {normalise(a) for a in q["accept"]}
    return response == q["answer"]


def correct_answer_text(q):
    if q["pairs"]:
        return "; ".join(f"{k} → {v}" for k, v in q["pairs"].items())
    return q["answer"]


# ------------------------------------------------------------------ selection
def balanced_sample(pool, n, rng):
    """Round-robin across topics so a short game still covers many topics."""
    by_topic = {}
    for q in pool:
        by_topic.setdefault(q["topic"], []).append(q["id"])
    for ids in by_topic.values():
        rng.shuffle(ids)
    topics = list(by_topic)
    rng.shuffle(topics)
    picked = []
    while len(picked) < n and any(by_topic.values()):
        for t in topics:
            if by_topic[t] and len(picked) < n:
                picked.append(by_topic[t].pop())
    rng.shuffle(picked)
    return picked


def adaptive_next(s):
    """Pick the next question at the current level, favouring unseen topics."""
    used = set(s.order)
    level = s.level
    for offset in (0, 1, -1, 2, -2):
        lvl = level + offset
        if 0 <= lvl < len(DIFFICULTIES):
            pool = [q for q in BANK if q["id"] not in used
                    and q["difficulty"] == DIFFICULTIES[lvl]
                    and q["topic"] in s.topics]
            if pool:
                seen = [BY_ID[i]["topic"] for i in s.order]
                least = min(seen.count(q["topic"]) for q in pool)
                fresh = [q for q in pool if seen.count(q["topic"]) == least]
                return s.rng.choice(fresh)["id"]
    return None


# ------------------------------------------------------------------ game state
def new_game(player, level, n_questions, topics, timed, seed=None):
    s = st.session_state
    s.rng = random.Random(seed)
    s.player, s.level_name, s.timed = player.strip() or "Anonymous", level, timed
    s.topics = topics
    s.adaptive = level == "Adaptive"
    s.level = 1                     # adaptive starts at Medium
    s.n_questions = n_questions
    pool = [q for q in BANK if q["topic"] in topics
            and (level in ("Mixed", "Adaptive") or q["difficulty"] == level)]
    s.n_questions = min(n_questions, len(pool))
    s.order = [] if s.adaptive else balanced_sample(pool, s.n_questions, s.rng)
    if s.adaptive:
        s.order.append(adaptive_next(s))
    s.idx, s.score, s.streak, s.best_streak = 0, 0, 0, 0
    s.results = []
    s.fifty_left, s.flips_left = FIFTY_FIFTY_PER_GAME, FLIPS_PER_GAME
    s.game_start = time.time()
    s.saved = False
    s.stage = "play"
    start_question()


def start_question():
    s = st.session_state
    q = BY_ID[s.order[s.idx]]
    s.q_start = time.time()
    s.submitted = False
    s.used_hint = s.used_fifty = False
    s.removed = []
    s.last = None
    opts = list(q["options"] or [])
    if q["type"] not in ("True/False", "Assertion-Reason"):
        s.rng.shuffle(opts)
    s.shown_options = opts
    if q["pairs"]:
        rights = list(q["pairs"].values())
        s.rng.shuffle(rights)
        s.match_rights = rights


def time_left(q):
    return TIME_LIMIT_S[q["difficulty"]] - (time.time() - st.session_state.q_start)


def record_answer(q, response, timed_out=False):
    s = st.session_state
    correct = (not timed_out) and is_correct(q, response)
    elapsed = time.time() - s.q_start
    points, notes = 0, []
    if correct:
        points = BASE_POINTS[q["difficulty"]]
        notes.append(f"+{points} base ({q['difficulty']})")
        for used, name in ((s.used_hint, "hint"), (s.used_fifty, "50:50")):
            if used:
                points = int(points * LIFELINE_MULTIPLIER)
                notes.append(f"×{LIFELINE_MULTIPLIER} {name} used")
        if s.timed and elapsed < TIME_LIMIT_S[q["difficulty"]] / 2:
            points += SPEED_BONUS
            notes.append(f"+{SPEED_BONUS} speed bonus")
        s.streak += 1
        if s.streak >= STREAK_THRESHOLD:
            points += STREAK_BONUS
            notes.append(f"+{STREAK_BONUS} streak ×{s.streak} 🔥")
    else:
        s.streak = 0
    s.best_streak = max(s.best_streak, s.streak)
    s.score += points
    s.results.append(dict(
        id=q["id"], topic=q["topic"], type=q["type"],
        difficulty=q["difficulty"], correct=correct, points=points,
        response=response if not isinstance(response, dict)
        else "; ".join(f"{k} → {v}" for k, v in response.items()),
        time_s=round(elapsed, 1), hint=s.used_hint, fifty=s.used_fifty,
        timed_out=timed_out))
    if s.adaptive:  # move up a level after a correct answer, down after a miss
        s.level = min(s.level + 1, 2) if correct else max(s.level - 1, 0)
    s.submitted = True
    s.last = dict(correct=correct, points=points, notes=notes,
                  timed_out=timed_out)


def next_question():
    s = st.session_state
    s.idx += 1
    if s.idx >= s.n_questions:
        s.stage = "result"
        return
    if s.adaptive:
        nxt = adaptive_next(s)
        if nxt is None:
            s.stage = "result"
            return
        s.order.append(nxt)
    start_question()


def flip_question():
    """KBC-style lifeline: swap the current question for an unseen one."""
    s = st.session_state
    cur = BY_ID[s.order[s.idx]]
    used = set(s.order)
    pool = [q["id"] for q in BANK if q["id"] not in used
            and q["topic"] in s.topics and q["difficulty"] == cur["difficulty"]]
    pool = pool or [q["id"] for q in BANK if q["id"] not in used
                    and q["topic"] in s.topics]
    if not pool:
        st.toast("No unseen question left to flip to.")
        return
    s.order[s.idx] = s.rng.choice(pool)
    s.flips_left -= 1
    start_question()


# ------------------------------------------------------------------ figures
def show_figure(kind):
    if kind == "graph":
        lines = ["digraph G { rankdir=LR; node [shape=circle, fontsize=11];"]
        for n, h in HEUR.items():
            extra = ', style=filled, fillcolor="#c8e6c9"' if n == "G" else ""
            lines.append(f'{n} [label="{n}\\nh={h}"{extra}];')
        for (u, v), w in EDGES.items():
            lines.append(f'{u} -> {v} [label="{w}"];')
        lines.append("}")
        st.graphviz_chart("\n".join(lines))
    elif kind == "landscape":
        st.bar_chart(pd.DataFrame({"objective value": LANDSCAPE},
                                  index=range(len(LANDSCAPE))), height=200)
    elif kind == "australia":
        dot = ["graph AU { layout=neato; node [shape=ellipse];"]
        dot += [f"{a} -- {b};" for a, b in AUSTRALIA] + ["T;", "}"]
        st.graphviz_chart("\n".join(dot))
    elif kind == "puzzle":
        def grid(b, title):
            cells = "".join(f"<div>{'' if x == 0 else x}</div>"
                            for row in b for x in row)
            return (f"<div style='display:inline-block;text-align:center'>"
                    f"<b>{title}</b><br><div class='grid'>{cells}</div></div>")
        st.markdown(grid(PUZZLE_START, "Start") + grid(PUZZLE_GOAL, "Goal"),
                    unsafe_allow_html=True)


# ------------------------------------------------------------------ timer
@st.fragment(run_every=1)
def countdown(q):
    s = st.session_state
    if s.submitted or s.stage != "play":
        return
    left = time_left(q)
    if left <= 0:
        st.rerun()          # full rerun → main flow records the timeout
    limit = TIME_LIMIT_S[q["difficulty"]]
    st.progress(max(left, 0) / limit, text=f"⏱️ {int(left)} s left")


